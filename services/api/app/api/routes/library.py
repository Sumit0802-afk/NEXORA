from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from app.api.deps import get_current_user
from app.db.models import LibraryFavorite, User
from app.db.session import get_db
from app.domain.circulation import circulation_issues
from app.domain.geometry import spatial_issues
from app.domain.library import catalog

router = APIRouter(prefix="/library", tags=["library"])


def _csv(value: str | None) -> list[str]:
    return [v.strip() for v in (value or "").split(",") if v.strip()]


def _ints(value: str | None) -> list[int]:
    out = []
    for v in _csv(value):
        if not v.isdigit():
            raise HTTPException(status_code=422, detail=f"Expected a number list, got '{value}'.")
        out.append(int(v))
    return out


@router.get("")
def list_designs(
    q: str = Query(default="", max_length=100),
    tags: str | None = None,
    floors: str | None = None,
    bedrooms: str | None = None,
    min_area: int = Query(default=0, alias="minArea", ge=0),
    max_area: int = Query(default=10**9, alias="maxArea", ge=0),
    favourites: bool = False,
    sort: str = Query(default="score", pattern="^(score|area_asc|area_desc|bedrooms)$"),
    limit: int = Query(default=24, ge=1, le=60),
    offset: int = Query(default=0, ge=0),
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict[str, Any]:
    """Search and filter the library. Returns a page plus the favourites among it; `ready` is false while it builds."""
    if not catalog.ready:
        return {"ready": False, "progress": catalog.progress, "target": catalog.target, "error": catalog.error,
                "total": 0, "items": [], "favourites": []}
    liked = set(db.execute(select(LibraryFavorite.design_id).where(LibraryFavorite.user_id == user.id)).scalars())
    result = catalog.query(
        q=q, tags=_csv(tags), floors=_ints(floors), bedrooms=_ints(bedrooms), min_area=min_area, max_area=max_area,
        ids=liked if favourites else None, sort=sort, limit=limit, offset=offset,
    )
    return {"ready": True, **result, "favourites": [e["id"] for e in result["items"] if e["id"] in liked]}


@router.get("/facets")
def facets() -> dict[str, Any]:
    if not catalog.ready:
        return {"ready": False, "progress": catalog.progress, "target": catalog.target}
    return {"ready": True, **catalog.facets()}


@router.get("/favourites")
def favourite_ids(db: Session = Depends(get_db), user: User = Depends(get_current_user)) -> dict[str, list[str]]:
    ids = db.execute(select(LibraryFavorite.design_id).where(LibraryFavorite.user_id == user.id)).scalars().all()
    return {"ids": list(ids)}


@router.put("/favourites/{design_id}", status_code=204)
def add_favourite(design_id: str, db: Session = Depends(get_db), user: User = Depends(get_current_user)) -> None:
    if design_id not in catalog.entries:
        raise HTTPException(status_code=404, detail="Design not found")
    if db.get(LibraryFavorite, (user.id, design_id)) is None:
        db.add(LibraryFavorite(user_id=user.id, design_id=design_id))
        db.commit()


@router.delete("/favourites/{design_id}", status_code=204)
def remove_favourite(design_id: str, db: Session = Depends(get_db), user: User = Depends(get_current_user)) -> None:
    db.execute(delete(LibraryFavorite).where(LibraryFavorite.user_id == user.id, LibraryFavorite.design_id == design_id))
    db.commit()


@router.get("/{design_id}")
def get_design(design_id: str, db: Session = Depends(get_db), user: User = Depends(get_current_user)) -> dict[str, Any]:
    """Full editable design (rooms, walls, openings, every floor) plus its metadata and engine checks."""
    found = catalog.design_for(design_id) if catalog.ready else None
    if not found:
        raise HTTPException(status_code=404, detail="Design not found")
    design = found["design"]
    return {
        "entry": found["entry"],
        "design": design,
        "highlights": found["candidate"].get("highlights", []),
        "warnings": found["candidate"].get("warnings", []),
        "checks": {"spatial": spatial_issues(design), "circulation": circulation_issues(design)},
        "favourite": db.get(LibraryFavorite, (user.id, design_id)) is not None,
        "origin": "Generated by the NEXORA layout engine. A conceptual starting point, not a construction drawing.",
    }
